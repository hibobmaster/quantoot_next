export function tr(en, zhHans, zhHant) {
  return `data-zh-hans="${escapeAttr(zhHans)}" data-zh-hant="${escapeAttr(zhHant)}"`;
}

export function escapeAttr(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

